-- ---------------------------------------------------------
-- חלק 1: הדגמת ROLLBACK (ביטול שינויים)
-- ---------------------------------------------------------

-- 1. נפתח טרנזקציה
BEGIN;

-- 2. נבצע שינוי דרסטי (למשל: נמחק את כל סוגי החדרים!)
DELETE FROM ROOMTYPE;

-- 📸 צילום 1: הריצי SELECT * FROM ROOMTYPE; ותראי שהטבלה ריקה. צלמי למרצה.

-- 3. נתחרט ונבטל הכל
ROLLBACK;

-- 📸 צילום 2: הריצי שוב SELECT * FROM ROOMTYPE; ותראי שהכל חזר למקומו באורח פלא!


-- ---------------------------------------------------------
-- חלק 2: הדגמת COMMIT (אישור סופי של שינויים)
-- ---------------------------------------------------------

-- 1. נפתח טרנזקציה חדשה
BEGIN;

-- 2. נעדכן שם של סטטוס חדר (למשל נשנה את 'Available' ל-'Ready to Use')
UPDATE ROOMSTATUS 
SET StatusName = 'Ready to Use' 
WHERE StatusName = 'Available';

-- 3. נאשר את השינוי סופית
COMMIT;

-- 📸 צילום 3: הריצי SELECT * FROM ROOMSTATUS; ותראי שהשם השתנה ונשמר גם אחרי ה-COMMIT.