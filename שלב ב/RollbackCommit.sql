-- ---------------------------------------------------------
-- חלק 1: הדגמת ROLLBACK (ביטול שינויים)
-- ---------------------------------------------------------

-- שלב 1: מראים את מצב בסיס הנתונים לפני העדכון
-- (להריץ ולשמור צילום מסך של התוצאה עבור הדו"ח)
SELECT * FROM SPECIALOFFER WHERE OfferID = 1;

-- פותחים טרנזקציה
BEGIN; 

-- שלב 2: מבצעים עדכון (למשל, שינוי אחוז ההנחה למבצע ספציפי)
UPDATE SPECIALOFFER 
SET DiscountPercentage = 90.00 
WHERE OfferID = 1;

-- שלב 3: מראים את מצב בסיס הנתונים לאחר העדכון (בתוך הטרנזקציה)
-- (להריץ ולשמור צילום מסך - יראו שההנחה השתנתה ל-90)
SELECT * FROM SPECIALOFFER WHERE OfferID = 1;

-- שלב 4: מבצעים ביטול של השינוי
ROLLBACK;

-- שלב 5: מראים כי בסיס הנתונים חזר לקדמותו
-- (להריץ ולשמור צילום מסך - יראו שההנחה חזרה למספר המקורי)
SELECT * FROM SPECIALOFFER WHERE OfferID = 1;


-- ---------------------------------------------------------
-- חלק 2: הדגמת COMMIT (אישור סופי של שינויים)
-- ---------------------------------------------------------

-- שלב 1: מראים את מצב בסיס הנתונים לפני העדכון
-- (להריץ ולשמור צילום מסך של התוצאה עבור הדו"ח)
SELECT * FROM ROOMSTATUS WHERE StatusID = 1;

-- פותחים טרנזקציה חדשה
BEGIN;

-- שלב 2: מבצעים עדכון לבסיס הנתונים (שינוי שם הסטטוס)
UPDATE ROOMSTATUS 
SET StatusName = 'Ready to Use' 
WHERE StatusID = 1;

-- שלב 3: מראים את מצב בסיס הנתונים לאחר העדכון
-- (להריץ ולשמור צילום מסך - יראו שהשם השתנה)
SELECT * FROM ROOMSTATUS WHERE StatusID = 1;

-- שלב 4: מאשרים את השינוי סופית
COMMIT;

-- שלב 5: מראים כי המצב נשאר כפי שהיה לאחר העדכון וה-COMMIT
-- (להריץ ולשמור צילום מסך אחרון - השם נשאר מעודכן)
SELECT * FROM ROOMSTATUS WHERE StatusID = 1;