-- =======================================================================
-- תוכנית ראשית 1: בדיקת עלויות תחזוקה ועדכון סטטוס חדר בהתאם לתוצאה
-- תיאור: התוכנית מזמנת פונקציה ופרוצדורה. תחילה היא בודקת את עלות התיקונים 
--        של חדר מסוים בעזרת הפונקציה. אם נמצאו עלויות (גדול מ-0), 
--        היא קוראת לפרוצדורה ומעבירה את החדר לסטטוס 'Dirty' לטובת ניקיון.
-- =======================================================================

DO $$
DECLARE
    v_room_number INT := 1001; -- מספר החדר על הדלת
    v_room_id INT;             -- המזהה הפנימי
    v_total_cost NUMERIC;
BEGIN
    RAISE NOTICE '--- תחילת תוכנית בדיקת תחזוקה לחדר % ---', v_room_number;
    
    -- שולפים את המזהה הפנימי לפי מספר החדר כדי שהפונקציה תעבוד נכון
    SELECT RoomID INTO v_room_id FROM ROOM WHERE RoomNumber = v_room_number;
    
    -- קריאה לפונקציה עם המזהה הפנימי הנכון (v_room_id)
    v_total_cost := Get_Room_Total_Maintenance_Cost(v_room_id);
    
    IF v_total_cost IS NULL THEN
        v_total_cost := 0;
    END IF;
    
    RAISE NOTICE 'סך הוצאות התחזוקה שנמצאו עבור חדר זה: % שקלים.', v_total_cost;
    
    IF v_total_cost > 0 THEN
        RAISE NOTICE 'מערכת מזהה עלויות תיקון. קוראת לפרוצדורה Update_Room_Status...';
        -- הפרוצדורה מקבלת את מספר החדר הרגיל (v_room_number)
        CALL Update_Room_Status(v_room_number, 'Dirty');
    ELSE
        RAISE NOTICE 'לא נמצאו עלויות תחזוקה קודמות. אין צורך לשנות סטטוס לחדר זה.';
    END IF;
    
    RAISE NOTICE '--- סיום תוכנית 1 בהצלחה ---';
END;
$$;

-- =======================================================================
-- תוכנית ראשית 2: הפעלת הנחות והדגמת מנגנון תפיסת חריגות (Exception Handling)
-- תיאור: התוכנית מזמנת פרוצדורה ופונקציה. תחילה היא קוראת לפרוצדורה המעניקה
--        הנחה לעונה מסוימת. לאחר מכן, היא מנסה לקרוא לפונקציית שליפת תעריפים 
--        עם מזהה סוג חדר שגוי (9999). במקום קריסת מערכת, בלוק ה-EXCEPTION 
--        תופס את החריגה שמייצרת הפונקציה ומדפיס הודעה מבוקרת ללוג.
-- =======================================================================

DO $$
DECLARE
    v_room_type_id INT := 9999; 
    v_rates_cursor REFCURSOR;
BEGIN
    RAISE NOTICE '--- תחילת תוכנית חיפוש תעריפים עם הגנת שגיאות ---';
    
    -- זימון הפרוצדורה כדי לעמוד בדרישות המטלה
    RAISE NOTICE 'מפעיל קריאה לפרוצדורת הנחות כחלק מתהליך הבדיקה...';
    CALL Apply_Discount_To_Season(1, 5);
    
    -- זימון הפונקציה (שתזרוק את השגיאה כמתוכנן)
    RAISE NOTICE 'מנסה לפתוח סמן (Cursor) עבור סוג חדר %...', v_room_type_id;
    v_rates_cursor := Get_Active_Rates_For_RoomType(v_room_type_id);
    
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE '!!! המערכת זיהתה ותפסה חריגה בצורה מאובטחת !!!';
        RAISE NOTICE 'הודעת השגיאה המקורית מהפונקציה: %', SQLERRM;
        RAISE NOTICE 'בוצע ביטול (Rollback) אוטומטי לפעולה. המערכת ממשיכה לעבוד כרגיל.';
END;
$$;